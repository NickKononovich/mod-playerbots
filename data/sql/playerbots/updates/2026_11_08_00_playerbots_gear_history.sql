-- [guild15] every gear change of a guild bot (user 2026-11-08): the change, why and who decided, and a FULL snapshot of
-- its equipment after it (entry e0..e18 and item level i0..i18 per equipment slot, enchants / gems as text); a
-- "baseline" row at its first login with this table
CREATE TABLE IF NOT EXISTS `playerbots_gear_history` (
    `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
    `guid` INT UNSIGNED NOT NULL,
    `name` VARCHAR(12) NOT NULL DEFAULT '',
    `level` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `class` TINYINT UNSIGNED NOT NULL DEFAULT 0,
    `spec` VARCHAR(32) NOT NULL DEFAULT '',
    `slot` TINYINT UNSIGNED NOT NULL DEFAULT 255 COMMENT '255 = baseline',
    `old_entry` INT UNSIGNED NOT NULL DEFAULT 0,
    `old_ilvl` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `new_entry` INT UNSIGNED NOT NULL DEFAULT 0,
    `new_ilvl` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `source` VARCHAR(16) NOT NULL DEFAULT 'other' COMMENT 'quest reward / loot / vendor buy / guild transfer / craft / bank / other / baseline',
    `decider` VARCHAR(8) NOT NULL DEFAULT 'none' COMMENT 'leader / none (no leader decision: [alert] DOUBLE_DECISION) / baseline',
    `reason` VARCHAR(255) NOT NULL DEFAULT '',
    `e0` INT UNSIGNED NOT NULL DEFAULT 0,
    `e1` INT UNSIGNED NOT NULL DEFAULT 0,
    `e2` INT UNSIGNED NOT NULL DEFAULT 0,
    `e3` INT UNSIGNED NOT NULL DEFAULT 0,
    `e4` INT UNSIGNED NOT NULL DEFAULT 0,
    `e5` INT UNSIGNED NOT NULL DEFAULT 0,
    `e6` INT UNSIGNED NOT NULL DEFAULT 0,
    `e7` INT UNSIGNED NOT NULL DEFAULT 0,
    `e8` INT UNSIGNED NOT NULL DEFAULT 0,
    `e9` INT UNSIGNED NOT NULL DEFAULT 0,
    `e10` INT UNSIGNED NOT NULL DEFAULT 0,
    `e11` INT UNSIGNED NOT NULL DEFAULT 0,
    `e12` INT UNSIGNED NOT NULL DEFAULT 0,
    `e13` INT UNSIGNED NOT NULL DEFAULT 0,
    `e14` INT UNSIGNED NOT NULL DEFAULT 0,
    `e15` INT UNSIGNED NOT NULL DEFAULT 0,
    `e16` INT UNSIGNED NOT NULL DEFAULT 0,
    `e17` INT UNSIGNED NOT NULL DEFAULT 0,
    `e18` INT UNSIGNED NOT NULL DEFAULT 0,
    `i0` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i1` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i2` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i3` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i4` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i5` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i6` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i7` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i8` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i9` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i10` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i11` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i12` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i13` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i14` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i15` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i16` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i17` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `i18` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    `enchants` VARCHAR(1024) NOT NULL DEFAULT '' COMMENT 'slot:enchant/gem1,gem2,gem3;...',
    `avg_ilvl` FLOAT NOT NULL DEFAULT 0,
    `gear_score` INT UNSIGNED NOT NULL DEFAULT 0,
    `time` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    KEY `idx_guid_time` (`guid`, `time`),
    KEY `idx_guid_slot` (`guid`, `slot`, `time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
